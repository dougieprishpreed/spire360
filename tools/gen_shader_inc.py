#!/usr/bin/env python3
"""HLSL source -> C string table (engine/gfx/shaders/<name>_hlsl.inc), for
the PC D3D9 renderer, which compiles its shaders at startup. The Xbox 360
build compiles the .hlsl with the XDK's fxc instead.

    python3 tools/gen_shader_inc.py engine/gfx/shaders/canvas.hlsl engine/gfx/shaders/effects.hlsl

For a file with effect entry points (ps_e<id>, effects.hlsl) it also writes
<name>_build.cmd, which the XDK project runs: fxc for each entry point, then
<name>_ps.h with the table g_effect_ps[id] of their bytecode.
"""
import os
import re
import sys

for src in sys.argv[1:]:
    base = os.path.splitext(src)[0]
    out = base + "_hlsl.inc"
    with open(src, encoding="utf-8") as f:
        text = f.read()
    lines = text.splitlines()
    with open(out, "w", newline="\n") as f:
        f.write(f"/* Generated from {os.path.basename(src)} by tools/gen_shader_inc.py. Do not edit. */\n")
        for ln in lines:
            esc = ln.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'"{esc}\\n",\n')
    print(out)
    ids = sorted({int(x) for x in re.findall(r"\bfloat4\s+ps_e(\d+)\s*\(", text)})
    if not ids:
        continue
    name = os.path.basename(base)
    cmd = base + "_build.cmd"
    with open(cmd, "w", newline="\r\n") as f:
        f.write("@echo off\n")
        f.write(f"rem Generated from {name}.hlsl by tools/gen_shader_inc.py. Do not edit.\n")
        f.write(f"rem {name}_build.cmd <fxc.exe> <{name}.hlsl> <output folder with a trailing backslash>\n")
        for i in ids:
            f.write(f'"%~1" /nologo /T ps_3_0 /E ps_e{i} /Vn g_ps_e{i} /Fh "%~3{name}_ps_e{i}.h" "%~2" || exit /b 1\n')
        f.write(f'> "%~3{name}_ps.h" echo /* Generated by {name}_build.cmd. */\n')
        for i in ids:
            f.write(f'>> "%~3{name}_ps.h" echo #include "{name}_ps_e{i}.h"\n')
        table = ", ".join(f"g_ps_e{i}" if i in ids else "0" for i in range(max(ids) + 1))
        table = table.replace("g_ps_e0", "0", 1) if 0 not in ids else table
        f.write(f'>> "%~3{name}_ps.h" echo static const BYTE* const g_effect_ps[] = {{ {table} }};\n')
        f.write(f'>> "%~3{name}_ps.h" echo static const int g_effect_ps_count = {max(ids) + 1};\n')
    print(cmd)
