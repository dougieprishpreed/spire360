#!/usr/bin/env python3
"""Regenerate the translated C for the XDK test projects and check it on PC.

    gen_xdk_tests.py --wasi-sdk DIR [--w2c2 PATH] [--no-check]

For xdk/selftest (runtime/tests/guest_selftest.c) and xdk/bench (bench.c):
compile to wasm with wasi-sdk, translate with w2c2 into <project>/gen/, write
the config header module_main.c reads, then build module_main.c + runtime
with gcc (and powerpc-linux-gnu-gcc under qemu when available) and run it, so
what the XDK compiles has already passed on a little- and a big-endian host.
The generated files are committed: building the XEX needs only the XDK.
"""
import argparse
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RT = os.path.join(ROOT, "runtime")
W2C2_INC = os.path.join(ROOT, "third_party", "w2c2", "w2c2")
XDK = os.path.join(ROOT, "xdk")


def run(cmd, **kw):
    print("+", " ".join(cmd), flush=True)
    kw.setdefault("check", True)
    return subprocess.run(cmd, **kw)


def c_string(text):
    out = []
    for line in text.splitlines(True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append('    "' + esc + '"')
    return "\n".join(out) if out else '    ""'


def generate(a, w2c2, name, source, module, script, expected, setup_data):
    gen = os.path.join(XDK, name, "gen")
    shutil.rmtree(gen, ignore_errors=True)
    os.makedirs(gen)
    wasm = os.path.join(a.build, name + "_src.wasm")
    run([os.path.join(a.wasi_sdk, "bin", "clang"), "--sysroot", os.path.join(a.wasi_sdk, "share", "wasi-sysroot"),
         "-O2", "-D_WASI_EMULATED_PROCESS_CLOCKS", source, "-o", wasm, "-lm"])
    shutil.copy2(wasm, os.path.join(a.build, module + ".wasm"))
    run([w2c2, os.path.join(a.build, module + ".wasm"), os.path.join(gen, module + ".c")], stderr=subprocess.DEVNULL)
    run([sys.executable, os.path.join(ROOT, "tools", "w2c2_imports.py"), os.path.join(gen, module + ".h"),
         "--stubs", os.path.join(gen, "stubs.c"), "--quiet"], check=False)
    prefix = "m%d_%s" % (len(module), module)
    with open(os.path.join(gen, "module_config.h"), "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_xdk_tests.py - do not edit. */\n")
        f.write('#define SRT_MODULE %s\n#define SRT_MODULE_HEADER "%s.h"\n' % (prefix, module))
        f.write('#define SPIRE_ROOT "game:/spire360_%s"\n' % name)
        f.write("#define SPIRE_SCRIPT \\\n%s\n" % c_string(script).replace("\n", " \\\n"))
        if expected is not None:
            f.write("#define SPIRE_EXPECTED \\\n%s\n" % c_string(expected).replace("\n", " \\\n"))
        if setup_data:
            f.write("#define SPIRE_SETUP_DATA 1\n")
    return gen


def check(a, name, gen, cc, runner):
    """Build module_main.c for this machine (root redirected to a temp dir) and run it."""
    out = os.path.join(a.build, "%s_%s" % (name, cc.replace("/", "_")))
    root = os.path.join(a.build, "root_" + name)
    shutil.rmtree(root, ignore_errors=True)
    os.makedirs(root)
    srcs = [os.path.join(XDK, "common", "module_main.c"), os.path.join(RT, "src", "srt_core.c"),
            os.path.join(RT, "src", "srt_wasi.c"), os.path.join(RT, "src", "srt_wasi_p2.c"),
            os.path.join(RT, "src", "srt_plat_posix.c")] + \
           [os.path.join(gen, f) for f in sorted(os.listdir(gen)) if f.endswith(".c")]
    flags = ["-O2", "-w", "-std=gnu99", "-DW2C2_HOST_MEMORY", '-DSPIRE_ROOT_OVERRIDE="%s"' % root,
             "-I", os.path.join(RT, "include"), "-I", os.path.join(RT, "src"), "-I", W2C2_INC, "-I", gen]
    extra = (["-static"] if "powerpc" in cc else []) + a.cflags
    run([cc] + flags + extra + srcs + ["-o", out, "-lm", "-lpthread"])
    r = subprocess.run(runner + [out], capture_output=True, text=True, timeout=900)
    print(r.stdout[-1500:])
    verdict = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else "(no output)"
    return verdict


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wasi-sdk", default=os.environ.get("WASI_SDK_PATH"))
    ap.add_argument("--w2c2", default=os.environ.get("W2C2"))
    ap.add_argument("--build", default=os.path.join(ROOT, "out", "xdk-gen"))
    ap.add_argument("--no-check", action="store_true")
    ap.add_argument("--cflag", dest="cflags", action="append", default=[],
                    help="extra C flag for the checks (e.g. -DW2C2_PORTABLE_MATH, the XDK's math path)")
    a = ap.parse_args()
    if not a.wasi_sdk:
        sys.exit("set --wasi-sdk or WASI_SDK_PATH")
    os.makedirs(a.build, exist_ok=True)
    w2c2 = a.w2c2
    if not w2c2:
        b = os.path.join(a.build, "w2c2-build")
        run(["cmake", "-S", W2C2_INC, "-B", b, "-DCMAKE_BUILD_TYPE=Release"], stdout=subprocess.DEVNULL)
        run(["cmake", "--build", b, "--target", "w2c2", "-j4"], stdout=subprocess.DEVNULL)
        w2c2 = os.path.join(b, "w2c2")

    with open(os.path.join(RT, "tests", "script.txt")) as f:
        script = f.read()
    with open(os.path.join(RT, "tests", "expected.txt")) as f:
        # module_main.c captures stdout only; host_main's "exit" line is not output.
        expected = "".join(l for l in f.read().splitlines(True) if not l.startswith("exit "))

    projects = [
        ("selftest", os.path.join(RT, "tests", "guest_selftest.c"), "guest", script, expected, True),
        ("bench", os.path.join(XDK, "bench", "bench.c"), "bench", "", None, False),
    ]
    results = []
    for name, src, module, scr, exp, data in projects:
        gen = generate(a, w2c2, name, src, module, scr, exp, data)
        if a.no_check:
            continue
        results.append((name, "x86-64", check(a, name, gen, "gcc", [])))
        if shutil.which("powerpc-linux-gnu-gcc") and shutil.which("qemu-ppc"):
            results.append((name, "ppc-be/qemu", check(a, name, gen, "powerpc-linux-gnu-gcc", ["qemu-ppc"])))
    for r in results:
        print("%-9s %-12s %s" % r)


if __name__ == "__main__":
    main()
