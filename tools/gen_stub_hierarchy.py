#!/usr/bin/env python3
"""Writes logic/Spire.GodotStubs/Manual/Hierarchy.cs: the real Godot classes
between the hand-written stubs and GodotObject that Manual/ does not declare
(RefCounted, CanvasItem, Range, InputEventMouse, ...), with their real bases.

The hand-written stubs must compile on their own (the stub generator reads
them), and every stub class must derive from its real base (check-stubs).

  dotnet out/logic/apidump/Spire.ApiDump.dll --real-bases <GodotSharp.real.dll> > bases.tsv
  gen_stub_hierarchy.py bases.tsv
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANUAL = os.path.join(ROOT, "logic", "Spire.GodotStubs", "Manual")
OUT = os.path.join(MANUAL, "Hierarchy.cs")
DECL = re.compile(r'\b(?:class|struct|interface|enum)\s+([A-Za-z_][A-Za-z0-9_]*)')


def declared_types():
    """Full names (Outer/Inner) of every type declared in Manual/ (except Hierarchy.cs)."""
    names = set()
    for f in glob.glob(os.path.join(MANUAL, "*.cs")):
        if os.path.abspath(f) == OUT:
            continue
        src = open(f, encoding="utf-8").read()
        ns = re.search(r'^namespace\s+([\w.]+)\s*;', src, re.M).group(1)
        stack, pending, depth = [], None, 0
        for ln in src.split("\n"):
            code = re.sub(r'"(?:\\.|[^"\\])*"', '""', ln).split("//")[0]
            m = DECL.search(code)
            if m:
                pending = (stack[-1][0] + "/" if stack else ns + ".") + m.group(1)
                names.add(pending)
            for ch in code:
                if ch == "{":
                    depth += 1
                    if pending:
                        stack.append((pending, depth))
                        pending = None
                elif ch == "}":
                    if stack and stack[-1][1] == depth:
                        stack.pop()
                    depth -= 1
            if pending and code.rstrip().endswith(";"):
                pending = None
    return names


def cs(full):
    return "global::" + full.replace("/", ".")


def main():
    bases = dict(l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if "\t" in l)
    manual = declared_types()
    need = set()
    for t in manual:
        b = bases.get(t)
        while b and b.startswith("Godot") and b not in manual and b in bases:
            need.add(b)
            b = bases.get(b)
    # Outer classes of needed nested types must be declared (as partials) too.
    for t in list(need):
        while "/" in t:
            t = t.rsplit("/", 1)[0]
            if t not in manual:
                need.add(t)
    tree = {}
    for t in sorted(need):
        tree.setdefault(t.rsplit("/", 1)[0] if "/" in t else None, []).append(t)

    lines = ["// Generated by tools/gen_stub_hierarchy.py from the real GodotSharp.dll: the",
             "// real classes between the hand-written stubs and GodotObject, with their real",
             "// bases. Members come from Generated/GodotApi.g.cs. Do not edit; regenerate.",
             "#pragma warning disable CS0108",
             "namespace Godot;", ""]

    def emit(t, ind):
        name = t.rsplit("/", 1)[-1].rsplit(".", 1)[-1]
        b = bases.get(t)
        base = " : " + cs(b) if t in need and b and b != "System.Object" else ""
        new = "new " if "/" in t and t in need and b and b.startswith("Godot") else ""
        kids = tree.get(t, [])
        if kids:
            lines.append(f"{ind}public {new}partial class {name}{base}")
            lines.append(ind + "{")
            for k in kids:
                emit(k, ind + "    ")
            lines.append(ind + "}")
        else:
            lines.append(f"{ind}public {new}partial class {name}{base} {{ }}")

    for t in tree.get(None, []):
        if not t.startswith("Godot.") or t.count(".") != 1:
            sys.exit(f"unexpected namespace for {t}")
        emit(t, "")
    # Outer classes that exist in Manual/ but hold needed nested types.
    for outer in sorted(k for k in tree if k and k not in need):
        name = outer.rsplit(".", 1)[-1]
        lines.append(f"public partial class {name}")
        lines.append("{")
        for k in tree[outer]:
            emit(k, "    ")
        lines.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(need)} types -> {OUT}")


if __name__ == "__main__":
    main()
