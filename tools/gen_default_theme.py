#!/usr/bin/env python3
"""Godot's default Theme -> engine/scene/default_theme.inc.

The engine looks theme items up like Godot does (overrides, then the themes
of Control ancestors, then the default theme). The default theme comes from
the Godot build the game uses (4.5.1), dumped by
tools/godot/dump_default_theme.gd:

    godot --headless --path <empty project> --script tools/godot/dump_default_theme.gd -- dump.json
    python3 tools/gen_default_theme.py dump.json

Output: JSON in the converter's value encoding ({"t": "Color", "v": [...]},
inline resources as {"t": "Object", "class", "props"}), embedded as a C++
string table (VS2010 caps a single literal at 16 KB).
Icons are left out (the game draws its own textures).
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "converter"))
from spire_convert import scenes, variant  # noqa: E402

TYPES = None  # every type in the dump


def convert_value(v):
    if isinstance(v, dict):
        props = {}
        for k, x in v.items():
            if k in ("class", "script", "resource_name", "resource_local_to_scene", "resource_path"):
                continue
            props[k] = scenes._value(variant.parse_value(x), {})
        return {"t": "Object", "class": v["class"], "props": props}
    if isinstance(v, str):
        return scenes._value(variant.parse_value(v), {})
    return v


def main():
    dump = json.load(open(sys.argv[1]))
    out = {"default_font_size": dump["default_font_size"], "default_base_scale": dump["default_base_scale"],
           "types": {}}
    for t, items in sorted(dump["types"].items()):
        d = {}
        for k, v in sorted(items.items()):
            if k.startswith("icons/") or v is None:
                continue
            if k.startswith("fonts/"):
                d[k] = {"default_font": v}  # the theme's default font (FontFile) or a variation of it
            elif k == "base":
                d[k] = v
            else:
                d[k] = convert_value(v)
        out["types"][t] = d
    text = json.dumps(out, separators=(",", ":"), sort_keys=True)
    path = os.path.join(os.path.dirname(__file__), "..", "engine", "scene", "default_theme.inc")
    with open(path, "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_default_theme.py from Godot 4.5.1's default theme\n"
                " * (Godot Engine, MIT license, see THIRD_PARTY.md). Do not edit. */\n")
        for i in range(0, len(text), 1000):
            chunk = text[i:i + 1000].replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'"{chunk}",\n')
    print(f"{path}: {len(text)} bytes, {len(out['types'])} types")


if __name__ == "__main__":
    main()
