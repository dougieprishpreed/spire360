#!/usr/bin/env python3
"""Audit the imports of a w2c2-translated module against the Spire360 runtime.

    w2c2_imports.py <module.h> [--stubs out.c] [--runtime-src DIR]

Reads the import declarations from the header w2c2 generated, works out which
ones the runtime defines (by expanding its WASI_FN/P2_CLOCK/P2_POLL/SRT_IMPORT
macros), prints a report, and optionally writes a C file with a trapping stub
for every import the runtime lacks. The stubs make an unfinished port link;
calling one logs its readable name and traps.

Exit status: 0 if every import is implemented, 1 if stubs were needed.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_RUNTIME_SRC = os.path.join(os.path.dirname(HERE), "runtime", "src")

# Macro name -> mangled prefix (module part) used in runtime sources.
MACRO_PREFIXES = {
    "WASI_FN": "i22_wasiX5FsnapshotX5Fpreview1",
    "P2_CLOCK": "i33_wasiX3AclocksX2FmonotonicX2DclockX400X2E2X2E0",
    "P2_POLL": "i18_wasiX3AioX2FpollX400X2E2X2E0",
}

DECL_RE = re.compile(r"^(?P<ret>[A-Za-z0-9_]+)\s+(?P<name>i\d+_[A-Za-z0-9_]+)\((?P<args>[^)]*)\);\s*$")
MACRO_RE = re.compile(r"\b(?P<macro>WASI_FN|P2_CLOCK|P2_POLL)\(\s*(?P<len>\d+)\s*,\s*(?P<name>[A-Za-z0-9_]+)\s*\)")
DIRECT_RE = re.compile(r"\b(i\d+_[A-Za-z0-9_]+)\s*\(")


def mangle(s):
    """w2c2's name escaping: alphanumerics stay, everything else is X + hex."""
    out = []
    for ch in s:
        if ch.isalnum() and ch != "X":
            out.append(ch)
        else:
            out.append("X%02X" % ord(ch))
    return "".join(out)


def import_symbol(module, name):
    return "i%d_%s%d_%s" % (len(module), mangle(module), len(name), mangle(name))


def demangle_part(s):
    return re.sub(r"X([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), s)


def demangle(symbol):
    """i<len>_<module><len>_<name> -> (module, name)."""
    m = re.match(r"i(\d+)_(.*)$", symbol)
    if not m:
        return None, symbol
    mod_len = int(m.group(1))
    rest = m.group(2)
    # Walk the escaped module name until mod_len characters are consumed.
    i = 0
    chars = 0
    while i < len(rest) and chars < mod_len:
        if rest[i] == "X" and re.match(r"X[0-9A-F]{2}", rest[i:i + 3]):
            i += 3
        else:
            i += 1
        chars += 1
    module = demangle_part(rest[:i])
    tail = rest[i:]
    m2 = re.match(r"(\d+)_(.*)$", tail)
    if not m2:
        return module, tail
    # The name length is ambiguous when the module ends in digits; trust it.
    return module, demangle_part(m2.group(2))


def implemented_symbols(src_dir):
    syms = set()
    for fn in sorted(os.listdir(src_dir)):
        if not fn.endswith(".c"):
            continue
        with open(os.path.join(src_dir, fn), encoding="utf-8") as f:
            text = f.read()
        for m in MACRO_RE.finditer(text):
            prefix = MACRO_PREFIXES[m.group("macro")]
            syms.add("%s%s_%s" % (prefix, m.group("len"), m.group("name")))
        for m in DIRECT_RE.finditer(text):
            syms.add(m.group(1))
    return syms


def parse_imports(header):
    imports = []
    with open(header, encoding="utf-8") as f:
        for line in f:
            m = DECL_RE.match(line.strip())
            if m:
                imports.append((m.group("ret"), m.group("name"), m.group("args")))
    return imports


def write_stubs(path, missing, header):
    lines = [
        "/* Generated by tools/w2c2_imports.py - do not edit.",
        " * Trapping stubs for module imports the runtime does not implement. */",
        '#include "w2c2_base.h"',
        '#include "srt_plat.h"',
        "",
        "static void srt_missing_import(const char* what) {",
        '    static const char prefix[] = "[srt] unimplemented import: ";',
        "    srt_plat_log(2, prefix, sizeof(prefix) - 1);",
        "    srt_plat_log(2, what, strlen(what));",
        '    srt_plat_log(2, "\\n", 1);',
        "    trap(trapUnreachable);",
        "}",
        "",
    ]
    for ret, name, args in missing:
        module, field = demangle(name)
        arg_types = [a.strip() for a in args.split(",") if a.strip()]
        params = []
        uses = []
        for i, t in enumerate(arg_types):
            params.append("%s a%d" % (t, i))
            uses.append("    (void)a%d;" % i)
        readable = ("%s.%s" % (module, field)).replace("\\", "\\\\").replace('"', '\\"')
        lines.append("%s %s(%s) {" % (ret, name, ", ".join(params) or "void"))
        lines.extend(uses)
        lines.append('    srt_missing_import("%s");' % readable)
        if ret != "void":
            lines.append("    return 0;")
        lines.append("}")
        lines.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("header")
    ap.add_argument("--stubs")
    ap.add_argument("--runtime-src", default=DEFAULT_RUNTIME_SRC)
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()

    imports = parse_imports(a.header)
    have = implemented_symbols(a.runtime_src)
    missing = [imp for imp in imports if imp[1] not in have]

    if not a.quiet:
        by_module = {}
        for ret, name, args in imports:
            module, field = demangle(name)
            by_module.setdefault(module, []).append((field, name in have))
        for module in sorted(by_module):
            print(module)
            for field, ok in sorted(by_module[module]):
                print("  %s %s" % ("ok     " if ok else "MISSING", field))
        print("%d imports, %d implemented, %d missing" % (len(imports), len(imports) - len(missing), len(missing)))

    if a.stubs:
        write_stubs(a.stubs, missing, a.header)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
