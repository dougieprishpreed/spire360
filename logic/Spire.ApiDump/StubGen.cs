// Spire.ApiDump --gen-stubs <game.dll> <manual GodotSharp.dll> <real GodotSharp.dll> <out.cs>
//
// Generates C# for every GodotSharp type and member the game references that
// the hand-written stubs (logic/Spire.GodotStubs/Manual, compiled to the
// "manual" assembly) do not define. Signatures come from the real
// GodotSharp.dll the game ships, so the generated stub matches what the game
// was compiled against. Bodies do nothing and return default values: the
// engine is not there. Behaviour that matters is written by hand in Manual/.
//
// Re-run whenever the game updates (tools/build_logic.py --stage stubs).
using System.Text;
using Mono.Cecil;

static class StubGen
{
    private sealed class TypePlan
    {
        public TypeDefinition Real = null!;
        public bool ExistsInManual;
        public TypeDefinition? Manual;
        public readonly List<IMemberDefinition> Members = new();
        public readonly List<TypePlan> Nested = new();
        public TypePlan? Parent;
    }

    private static ModuleDefinition _real = null!;
    private static ModuleDefinition _manual = null!;
    private static readonly Dictionary<string, TypePlan> Plans = new();
    private static readonly List<string> Warnings = new();

    public static int Run(string game, string manual, string real, string outPath)
    {
        var resolver = new DefaultAssemblyResolver();
        resolver.AddSearchDirectory(Path.GetDirectoryName(Path.GetFullPath(real))!);
        var gameMod = ModuleDefinition.ReadModule(game, new ReaderParameters { AssemblyResolver = resolver });
        _real = ModuleDefinition.ReadModule(real, new ReaderParameters { AssemblyResolver = resolver });
        _manual = ModuleDefinition.ReadModule(manual);

        bool IsGodot(TypeReference t) => t.Scope?.Name is "GodotSharp" or "GodotSharp.dll";

        foreach (var tr in gameMod.GetTypeReferences().Where(IsGodot))
        {
            var rt = FindReal(tr);
            if (rt != null) Plan(rt);
            else Warnings.Add($"type {tr.FullName} not in real GodotSharp");
        }

        foreach (var mr in gameMod.GetMemberReferences())
        {
            var declRef = mr.DeclaringType.GetElementType();
            if (!IsGodot(declRef)) continue;
            var rt = FindReal(declRef);
            if (rt == null) continue;
            var plan = Plan(rt);
            IMemberDefinition? def = mr switch
            {
                MethodReference m => rt.Methods.FirstOrDefault(x => SameSig(x, m)),
                FieldReference f => rt.Fields.FirstOrDefault(x => x.Name == f.Name),
                _ => null,
            };
            if (def == null)
            {
                Warnings.Add($"member {declRef.FullName}::{mr.Name} not in real GodotSharp");
                continue;
            }
            if (plan.ExistsInManual && ManualHas(plan.Manual!, def)) continue;
            if (!plan.Members.Contains(def)) plan.Members.Add(def);
            // C# requires ==/!=, </>, <=/>= in pairs.
            if (def is MethodDefinition om && Partner(om.Name) is string partnerName)
            {
                var partner = rt.Methods.FirstOrDefault(x => x.Name == partnerName
                    && x.Parameters.Select(q => Norm(q.ParameterType)).SequenceEqual(om.Parameters.Select(q => Norm(q.ParameterType))));
                if (partner != null && !(plan.ExistsInManual && ManualHas(plan.Manual!, partner)) && !plan.Members.Contains(partner))
                    plan.Members.Add(partner);
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by Spire.ApiDump --gen-stubs from the GodotSharp API the game references");
        sb.AppendLine("// (GodotSharp is MIT licensed, (c) Godot Engine contributors). Do not edit: put real");
        sb.AppendLine("// behaviour in logic/Spire.GodotStubs/Manual/ and regenerate.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("#pragma warning disable CS0067, CS0108, CS0109, CS0114, CS0169, CS0414, CS0649, CS0660, CS0661, CS0809, CS8618");
        int typeCount = 0, memberCount = 0;
        foreach (var group in Plans.Values.Where(p => p.Parent == null)
                     .GroupBy(p => p.Real.Namespace).OrderBy(g => g.Key))
        {
            sb.AppendLine();
            sb.AppendLine($"namespace {group.Key}");
            sb.AppendLine("{");
            foreach (var plan in group.OrderBy(p => p.Real.Name))
                EmitType(sb, plan, 1, ref typeCount, ref memberCount);
            sb.AppendLine("}");
        }
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine($"generated {typeCount} type parts, {memberCount} members -> {outPath}");
        foreach (var w in Warnings.Distinct()) Console.WriteLine("  warning: " + w);
        return 0;
    }

    private static string? Partner(string op) => op switch
    {
        "op_Equality" => "op_Inequality",
        "op_Inequality" => "op_Equality",
        "op_LessThan" => "op_GreaterThan",
        "op_GreaterThan" => "op_LessThan",
        "op_LessThanOrEqual" => "op_GreaterThanOrEqual",
        "op_GreaterThanOrEqual" => "op_LessThanOrEqual",
        _ => null,
    };

    // ---- planning ----

    private static TypeDefinition? FindReal(TypeReference t)
    {
        if (t.IsNested)
        {
            var outer = FindReal(t.DeclaringType);
            return outer?.NestedTypes.FirstOrDefault(n => n.Name == t.Name);
        }
        return _real.GetType(t.Namespace, t.Name);
    }

    private static TypeDefinition? FindManual(TypeDefinition real)
    {
        if (real.IsNested)
        {
            var outer = FindManual(real.DeclaringType);
            return outer?.NestedTypes.FirstOrDefault(n => n.Name == real.Name);
        }
        return _manual.GetType(real.Namespace, real.Name);
    }

    private static TypePlan Plan(TypeDefinition real)
    {
        if (Plans.TryGetValue(real.FullName, out var p)) return p;
        p = new TypePlan { Real = real, Manual = FindManual(real) };
        p.ExistsInManual = p.Manual != null;
        Plans[real.FullName] = p;
        if (real.IsNested)
        {
            p.Parent = Plan(real.DeclaringType);
            p.Parent.Nested.Add(p);
        }
        // Every stub class derives from its real base, so the whole real
        // ancestry must exist (the game passes an InputEventMouseMotion where
        // an InputEventMouse is expected; NativeAOT-LLVM rejects a mismatch).
        if (real.BaseType != null && IsGodotType(real.BaseType))
        {
            var b = FindReal(real.BaseType.GetElementType());
            if (b != null) Plan(b);
        }
        // Enums and delegates are emitted whole.
        return p;
    }

    private static bool IsGodotType(TypeReference t) =>
        t.Scope?.Name is "GodotSharp" or "GodotSharp.dll" || t.Module == _real && t.Resolve()?.Module == _real;

    /// <summary>Type identity for signature matching: generic parameters by position, modifiers dropped.</summary>
    private static string Norm(TypeReference t) => t switch
    {
        ByReferenceType br => Norm(br.ElementType) + "&",
        RequiredModifierType rm => Norm(rm.ElementType),
        OptionalModifierType om => Norm(om.ElementType),
        ArrayType at => Norm(at.ElementType) + "[" + new string(',', at.Rank - 1) + "]",
        PointerType pt => Norm(pt.ElementType) + "*",
        GenericParameter gp => (gp.Type == GenericParameterType.Method ? "!!" : "!") + gp.Position,
        GenericInstanceType git => git.ElementType.FullName + "<" + string.Join(",", git.GenericArguments.Select(Norm)) + ">",
        _ => t.FullName,
    };

    private static bool SameSig(MethodDefinition d, MethodReference r) =>
        d.Name == r.Name && d.Parameters.Count == r.Parameters.Count
        && d.GenericParameters.Count == r.GenericParameters.Count
        && Norm(d.ReturnType) == Norm(r.ReturnType)
        && d.Parameters.Select(x => Norm(x.ParameterType)).SequenceEqual(r.Parameters.Select(x => Norm(x.ParameterType)));

    private static bool ManualHas(TypeDefinition manual, IMemberDefinition def)
    {
        if (ManualHasOwn(manual, def)) return true;
        // Inherited from a hand-written base (Godot stub or a BCL collection):
        // a generated no-op would hide the working member.
        for (var b = manual.BaseType; b != null;)
        {
            var bd = b.Scope == _manual || b.Module == _manual ? _manual.GetType(b.GetElementType().FullName.Replace('/', '+'))
                     ?? FindManualByName(b.GetElementType().FullName) : null;
            if (bd != null)
            {
                if (ManualHasOwn(bd, def)) return true;
                b = bd.BaseType;
                continue;
            }
            if (BclHas(b.GetElementType().FullName, def)) return true;
            break;
        }
        return false;
    }

    private static TypeDefinition? FindManualByName(string fullName)
    {
        foreach (var t in _manual.Types)
            if (t.FullName == fullName) return t;
        return null;
    }

    /// <summary>Does a BCL base type (List`1, Dictionary`2, ...) have a public member of this name and arity?</summary>
    private static bool BclHas(string fullName, IMemberDefinition def)
    {
        var t = Type.GetType(fullName);
        if (t == null) return false;
        const System.Reflection.BindingFlags F = System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance
                                                 | System.Reflection.BindingFlags.Static;
        switch (def)
        {
            case MethodDefinition m when m.IsGetter || m.IsSetter:
                var pname = m.Name[4..];
                if (pname == "Item") return t.GetProperties(F).Any(p => p.GetIndexParameters().Length > 0);
                return t.GetProperty(pname, F) != null;
            case MethodDefinition m when !m.IsConstructor:
                // Same name, arity and return type (List<T>.GetEnumerator returns a
                // struct; the Godot one returns IEnumerator<T>, a different member).
                return t.GetMethods(F).Any(x => x.Name == m.Name && x.GetParameters().Length == m.Parameters.Count
                                                && x.ReturnType.Name == m.ReturnType.Name);
        }
        return false;
    }

    private static bool ManualHasOwn(TypeDefinition manual, IMemberDefinition def)
    {
        switch (def)
        {
            case MethodDefinition m:
                if (manual.Methods.Any(x => SameSig(x, m))) return true;
                if (m.Name is "op_Implicit" or "op_Explicit"
                    && manual.Methods.Any(x => x.Name is "op_Implicit" or "op_Explicit"
                        && Norm(x.ReturnType) == Norm(m.ReturnType)
                        && x.Parameters.Select(q => Norm(q.ParameterType)).SequenceEqual(m.Parameters.Select(q => Norm(q.ParameterType)))))
                    return true;
                // A manual property with the same name blocks a generated accessor.
                if ((m.IsGetter || m.IsSetter) && manual.Properties.Any(p => p.Name == m.Name[4..]))
                {
                    Warnings.Add($"{manual.FullName}.{m.Name[4..]}: manual property lacks accessor {m.Name}; add it by hand");
                    return true;
                }
                if ((m.IsAddOn || m.IsRemoveOn) && manual.Events.Any(e => m.Name.EndsWith("_" + e.Name)))
                    return true;
                if (m.IsConstructor && m.Parameters.Count == 0 && !manual.Methods.Any(x => x.IsConstructor))
                    return true;
                return false;
            case FieldDefinition f:
                return manual.Fields.Any(x => x.Name == f.Name) || manual.Properties.Any(p => p.Name == f.Name);
        }
        return false;
    }

    // ---- emission ----

    private static string Ind(int n) => new string(' ', n * 4);

    private static string Access(TypeDefinition t) => "public";

    private static void EmitType(StringBuilder sb, TypePlan plan, int ind, ref int types, ref int members)
    {
        var t = plan.Real;
        if (plan.ExistsInManual && plan.Members.Count == 0 && plan.Nested.Count == 0) return;
        types++;
        var i = Ind(ind);
        var name = CsName(t.Name) + GenericDecl(t);

        if (t.IsEnum)
        {
            if (plan.ExistsInManual) return; // enums cannot be partial; manual wins
            var underlying = t.Fields.First(f => f.Name == "value__").FieldType;
            if (t.CustomAttributes.Any(a => a.AttributeType.Name == "FlagsAttribute")) sb.AppendLine($"{i}[System.Flags]");
            sb.AppendLine($"{i}public enum {name} : {Cs(underlying)}");
            sb.AppendLine($"{i}{{");
            foreach (var f in t.Fields.Where(f => f.IsStatic && f.HasConstant))
                sb.AppendLine($"{i}    {CsName(f.Name)} = {Convert.ToString(f.Constant, System.Globalization.CultureInfo.InvariantCulture)},");
            sb.AppendLine($"{i}}}");
            return;
        }
        if (t.BaseType?.FullName == "System.MulticastDelegate")
        {
            if (plan.ExistsInManual) return;
            var invoke = t.Methods.First(m => m.Name == "Invoke");
            sb.AppendLine($"{i}public delegate {Cs(invoke.ReturnType)} {name}({Params(invoke, false)});");
            return;
        }

        string kind;
        var src = plan.Manual ?? t;
        if (src.IsInterface) kind = "interface";
        else if (src.IsValueType) kind = "struct";
        else kind = "class";
        string mods = "";
        if (kind == "class" && src.IsAbstract && src.IsSealed) mods = "static ";
        else if (kind == "class" && src.IsSealed && !plan.ExistsInManual) mods = "sealed ";
        string baseClause = "";
        if (!plan.ExistsInManual && kind == "class" && t.BaseType != null && t.BaseType.FullName != "System.Object")
            baseClause = " : " + Cs(t.BaseType);
        if (!plan.ExistsInManual && kind == "struct" && t.Interfaces.Count > 0)
            baseClause = ""; // interfaces on structs are not needed by callers

        sb.AppendLine($"{i}{Access(t)} {mods}partial {kind} {name}{baseClause}");
        sb.AppendLine($"{i}{{");

        // Properties first (from accessor methods), then the rest.
        var accessors = plan.Members.OfType<MethodDefinition>().Where(m => m.IsGetter || m.IsSetter).ToList();
        foreach (var prop in accessors.Select(a => t.Properties.FirstOrDefault(p => p.GetMethod == a || p.SetMethod == a))
                     .Where(p => p != null).Distinct())
        {
            EmitProperty(sb, prop!, kind, ind + 1, mods == "static ");
            members++;
        }
        var emittedEvents = new HashSet<EventDefinition>();
        foreach (var m in plan.Members)
        {
            if (m is MethodDefinition md)
            {
                if (md.IsGetter || md.IsSetter) continue;
                if (md.IsAddOn || md.IsRemoveOn)
                {
                    var ev = t.Events.FirstOrDefault(e => e.AddMethod == md || e.RemoveMethod == md);
                    if (ev != null && emittedEvents.Add(ev))
                    {
                        sb.AppendLine($"{Ind(ind + 1)}public {(md.IsStatic ? "static " : "")}event {Cs(ev.EventType)} {CsName(ev.Name)};");
                        members++;
                    }
                    continue;
                }
                EmitMethod(sb, md, kind, ind + 1, plan);
                members++;
            }
            else if (m is FieldDefinition fd)
            {
                EmitField(sb, fd, ind + 1);
                members++;
            }
        }
        foreach (var n in plan.Nested.OrderBy(n => n.Real.Name))
            EmitType(sb, n, ind + 1, ref types, ref members);
        sb.AppendLine($"{i}}}");
    }

    private static void EmitField(StringBuilder sb, FieldDefinition f, int ind)
    {
        var i = Ind(ind);
        var mods = f.IsStatic ? "static " : "";
        if (f.HasConstant)
        {
            sb.AppendLine($"{i}public const {Cs(f.FieldType)} {CsName(f.Name)} = {Literal(f.Constant, f.FieldType)};");
            return;
        }
        // StringName constants (SignalName.X, MethodName.X) get their real names.
        if (f.IsStatic && f.FieldType.FullName == "Godot.StringName")
        {
            sb.AppendLine($"{i}public static readonly global::Godot.StringName {CsName(f.Name)} = \"{f.Name}\";");
            return;
        }
        sb.AppendLine($"{i}public {mods}{Cs(f.FieldType)} {CsName(f.Name)};");
    }

    private static void EmitProperty(StringBuilder sb, PropertyDefinition p, string kind, int ind, bool staticClass)
    {
        var i = Ind(ind);
        var acc = p.GetMethod ?? p.SetMethod!;
        bool isStatic = acc.IsStatic;
        var mods = isStatic ? "static " : (kind == "class" && acc.IsVirtual && !acc.DeclaringType.IsSealed ? "virtual " : "");
        if (kind == "interface") mods = "";
        string name = CsName(p.Name);
        string paramList = "";
        if (p.HasParameters)
        {
            name = "this";
            paramList = "[" + string.Join(", ", p.Parameters.Select((x, k) => $"{Cs(x.ParameterType)} p{k}")) + "]";
        }
        var get = p.GetMethod != null ? (kind == "interface" ? "get; " : "get => default; ") : "";
        var set = p.SetMethod != null ? (kind == "interface" ? "set; " : "set { } ") : "";
        sb.AppendLine($"{i}public {mods}{Cs(p.PropertyType)} {name}{paramList} {{ {get}{set}}}");
    }

    private static void EmitMethod(StringBuilder sb, MethodDefinition m, string kind, int ind, TypePlan plan)
    {
        var i = Ind(ind);
        if (m.IsConstructor)
        {
            if (m.IsStatic) return;
            var tname = CsName(m.DeclaringType.Name);
            var baseCall = "";
            // Generated classes derive from Godot classes whose stubs may only
            // have a parameterless constructor.
            sb.AppendLine($"{i}public {tname}({Params(m, false)}){baseCall} {{ {OutAssigns(m)}}}");
            return;
        }
        if (m.Name.StartsWith("op_"))
        {
            var op = OperatorName(m);
            if (op == null) return;
            sb.AppendLine($"{i}public static {op}({Params(m, false)}) {{ {OutAssigns(m)}return default; }}");
            return;
        }
        var mods = "";
        if (m.IsStatic) mods = "static ";
        else if (kind == "class" && m.IsVirtual && !m.IsFinal) mods = "virtual ";
        var vis = m.IsFamily || m.IsFamilyOrAssembly ? "protected" : "public";
        if (kind == "interface") { vis = ""; mods = m.IsStatic ? "static " : ""; }
        if (m.HasOverrides || m.Name.Contains('.')) return; // explicit interface impls are not callable by name
        var ret = Cs(m.ReturnType);
        var generic = m.HasGenericParameters ? "<" + string.Join(", ", m.GenericParameters.Select(g => CsName(g.Name))) + ">" : "";
        var head = $"{(vis.Length > 0 ? vis + " " : "")}{mods}{ret} {CsName(m.Name)}{generic}({Params(m, true)}){Constraints(m)}";
        if (kind == "interface")
        {
            sb.AppendLine($"{i}{head};");
            return;
        }
        var body = OutAssigns(m) + (m.ReturnType.FullName == "System.Void" ? "" : "return default; ");
        sb.AppendLine($"{i}{head} {{ {body}}}");
    }

    /// <summary>The real method's generic constraints: callers' own constrained
    /// generics only verify against a stub with the same constraints.</summary>
    private static string Constraints(MethodDefinition m)
    {
        var sb = new StringBuilder();
        foreach (var g in m.GenericParameters)
        {
            var parts = new List<string>();
            var a = g.Attributes;
            if ((a & GenericParameterAttributes.NotNullableValueTypeConstraint) != 0) parts.Add("struct");
            else if ((a & GenericParameterAttributes.ReferenceTypeConstraint) != 0) parts.Add("class");
            foreach (var c in g.Constraints)
            {
                var ct = c.ConstraintType;
                if (ct.FullName == "System.ValueType" && parts.Contains("struct")) continue;
                parts.Add(Cs(ct));
            }
            if ((a & GenericParameterAttributes.DefaultConstructorConstraint) != 0 && !parts.Contains("struct")) parts.Add("new()");
            if (parts.Count > 0) sb.Append($" where {CsName(g.Name)} : {string.Join(", ", parts)}");
        }
        return sb.ToString();
    }

    private static string OutAssigns(MethodDefinition m) =>
        string.Concat(m.Parameters.Select((p, k) => p.IsOut ? $"p{k} = default; " : ""));

    private static string Params(MethodDefinition m, bool allowParams) =>
        string.Join(", ", m.Parameters.Select((p, k) =>
        {
            var t = p.ParameterType;
            string prefix = "";
            if (t is ByReferenceType br)
            {
                prefix = p.IsOut ? "out " : p.IsIn || p.CustomAttributes.Any(a => a.AttributeType.Name == "IsReadOnlyAttribute") ? "in " : "ref ";
                t = br.ElementType;
            }
            if (t is RequiredModifierType rm) t = rm.ElementType;
            if (allowParams && k == m.Parameters.Count - 1 && p.CustomAttributes.Any(a => a.AttributeType.Name == "ParamArrayAttribute"))
                prefix = "params ";
            var def = p.HasDefault && p.HasConstant ? " = " + Literal(p.Constant, t) : "";
            if (p.IsOptional && !p.HasConstant) def = " = default";
            return $"{prefix}{Cs(t)} p{k}{def}";
        }));

    private static string? OperatorName(MethodDefinition m)
    {
        string ret = Cs(m.ReturnType);
        return m.Name switch
        {
            "op_Implicit" => $"implicit operator {ret}",
            "op_Explicit" => $"explicit operator {ret}",
            "op_Equality" => $"{ret} operator ==",
            "op_Inequality" => $"{ret} operator !=",
            "op_Addition" => $"{ret} operator +",
            "op_Subtraction" => $"{ret} operator -",
            "op_Multiply" => $"{ret} operator *",
            "op_Division" => $"{ret} operator /",
            "op_UnaryNegation" => $"{ret} operator -",
            "op_LessThan" => $"{ret} operator <",
            "op_GreaterThan" => $"{ret} operator >",
            "op_LessThanOrEqual" => $"{ret} operator <=",
            "op_GreaterThanOrEqual" => $"{ret} operator >=",
            "op_Modulus" => $"{ret} operator %",
            _ => null,
        };
    }

    private static string Literal(object? v, TypeReference t)
    {
        if (v == null) return t.IsValueType ? "default" : "null";
        var resolved = t.Resolve();
        if (resolved != null && resolved.IsEnum) return $"({Cs(t)}){Convert.ToInt64(v)}";
        return v switch
        {
            bool b => b ? "true" : "false",
            string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
            float f => float.IsNaN(f) ? "float.NaN" : float.IsPositiveInfinity(f) ? "float.PositiveInfinity" : float.IsNegativeInfinity(f) ? "float.NegativeInfinity" : f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
            double d => double.IsNaN(d) ? "double.NaN" : double.IsPositiveInfinity(d) ? "double.PositiveInfinity" : double.IsNegativeInfinity(d) ? "double.NegativeInfinity" : d.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
            long l => l + "L",
            ulong ul => ul + "UL",
            uint ui => ui + "U",
            _ => t.Resolve()?.IsEnum == true ? $"({Cs(t)}){Convert.ToInt64(v)}" : Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)!,
        };
    }

    private static readonly HashSet<string> Keywords = new()
    {
        "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue",
        "decimal","default","delegate","do","double","else","enum","event","explicit","extern","false","finally",
        "fixed","float","for","foreach","goto","if","implicit","in","int","interface","internal","is","lock","long",
        "namespace","new","null","object","operator","out","override","params","private","protected","public",
        "readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct","switch",
        "this","throw","true","try","typeof","uint","ulong","unchecked","unsafe","ushort","using","virtual","void",
        "volatile","while",
    };

    private static string CsName(string n)
    {
        var tick = n.IndexOf('`');
        if (tick >= 0) n = n[..tick];
        return Keywords.Contains(n) ? "@" + n : n;
    }

    private static string GenericDecl(TypeDefinition t)
    {
        // Only the type's own generic parameters (nested types repeat the outer ones).
        var own = t.GenericParameters.Skip(t.IsNested ? t.DeclaringType.GenericParameters.Count : 0).ToList();
        return own.Count == 0 ? "" : "<" + string.Join(", ", own.Select(g => CsName(g.Name))) + ">";
    }

    private static string Cs(TypeReference t)
    {
        switch (t)
        {
            case ByReferenceType br: return Cs(br.ElementType);
            case RequiredModifierType rm: return Cs(rm.ElementType);
            case OptionalModifierType om: return Cs(om.ElementType);
            case PointerType pt: return "nint"; // stubs never dereference
            case ArrayType at: return Cs(at.ElementType) + "[" + new string(',', at.Rank - 1) + "]";
            case GenericParameter gp: return CsName(gp.Name);
            case GenericInstanceType git:
            {
                var el = git.ElementType;
                if (el.FullName == "System.Nullable`1") return Cs(git.GenericArguments[0]) + "?";
                return QualifiedName(el, git.GenericArguments.ToList());
            }
        }
        return t.FullName switch
        {
            "System.Void" => "void",
            "System.Boolean" => "bool",
            "System.Byte" => "byte",
            "System.SByte" => "sbyte",
            "System.Int16" => "short",
            "System.UInt16" => "ushort",
            "System.Int32" => "int",
            "System.UInt32" => "uint",
            "System.Int64" => "long",
            "System.UInt64" => "ulong",
            "System.Single" => "float",
            "System.Double" => "double",
            "System.Decimal" => "decimal",
            "System.Char" => "char",
            "System.String" => "string",
            "System.Object" => "object",
            "System.IntPtr" => "nint",
            "System.UIntPtr" => "nuint",
            _ => QualifiedName(t, new List<TypeReference>()),
        };
    }

    private static string QualifiedName(TypeReference t, List<TypeReference> args)
    {
        // Distribute generic arguments over the nesting chain.
        var chain = new List<TypeReference>();
        for (var c = t; c != null; c = c.DeclaringType) chain.Insert(0, c);
        var sb = new StringBuilder("global::");
        if (!string.IsNullOrEmpty(chain[0].Namespace)) sb.Append(chain[0].Namespace).Append('.');
        int used = 0;
        for (int k = 0; k < chain.Count; k++)
        {
            var c = chain[k];
            if (k > 0) sb.Append('.');
            sb.Append(CsName(c.Name));
            var tick = c.Name.IndexOf('`');
            int n = tick >= 0 ? int.Parse(c.Name[(tick + 1)..]) : 0;
            if (n > 0)
            {
                if (args.Count >= used + n)
                    sb.Append('<').Append(string.Join(", ", args.Skip(used).Take(n).Select(Cs))).Append('>');
                else
                    sb.Append('<').Append(new string(',', n - 1)).Append('>');
                used += n;
            }
        }
        return sb.ToString();
    }
