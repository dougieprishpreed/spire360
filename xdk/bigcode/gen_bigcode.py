#!/usr/bin/env python3
"""Generate the big-code link test (milestone M0).

    gen_bigcode.py [--mb 64] [--out xdk/bigcode/gen]

The game logic compiles to tens of MB of PowerPC code. PPC relative branches
reach +-32 MB, so the XDK linker must insert branch islands (or refuse) once
code grows past that. This writes ~N MB of C: many files of unrolled integer
functions that call functions in far-away files, a main() that runs a
deterministic chain through them, and the checksum it must print. Then build
bigcode.vcxproj with the XDK and run it: it prints PASS or FAIL.

Also check: the linker's time and memory, the XEX size, and the .text size in
the map file.
"""
import argparse
import os
import random

MASK = 0xFFFFFFFF
OPS_PER_FN = 48          # ~1.5-2 KB of PPC code per function
FNS_PER_FILE = 200
DEPTH = 6
CHAIN = 4000


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mb", type=int, default=64, help="approximate code size in MB")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen"))
    ap.add_argument("--seed", type=int, default=360)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    n_fns = max(FNS_PER_FILE, a.mb * 1024 * 1024 // 1800)
    n_files = (n_fns + FNS_PER_FILE - 1) // FNS_PER_FILE
    n_fns = n_files * FNS_PER_FILE
    os.makedirs(a.out, exist_ok=True)
    for f in os.listdir(a.out):
        if f.endswith(".c") or f.endswith(".h"):
            os.remove(os.path.join(a.out, f))

    # f_i(x, d): x = ops_i(x); if d > 0: x = f_next(i)(x, d - 1); return x
    fns = []
    for i in range(n_fns):
        ops = [(rng.randrange(1, MASK) | 1, rng.randrange(1, 31), rng.randrange(0, MASK)) for _ in range(OPS_PER_FN)]
        # Calls go to a far file most of the time, so branches span the image.
        nxt = rng.randrange(n_fns)
        fns.append((ops, nxt))

    with open(os.path.join(a.out, "bigcode.h"), "w", newline="\n") as h:
        h.write("/* Generated by gen_bigcode.py - do not edit. */\n")
        h.write("typedef unsigned int u32;\n")
        h.write("typedef u32 (*bigfn)(u32, int);\n")
        h.write("extern const bigfn big_table[%d];\n" % n_fns)
        for i in range(n_fns):
            h.write("u32 big_%d(u32 x, int d);\n" % i)

    for fi in range(n_files):
        with open(os.path.join(a.out, "big_%04d.c" % fi), "w", newline="\n") as c:
            c.write('#include "bigcode.h"\n')
            for i in range(fi * FNS_PER_FILE, (fi + 1) * FNS_PER_FILE):
                ops, nxt = fns[i]
                c.write("u32 big_%d(u32 x, int d) {\n" % i)
                for (mul, sh, add) in ops:
                    c.write("    x = ((x * %uu) ^ (x >> %d)) + %uu;\n" % (mul, sh, add))
                c.write("    if (d > 0) x = big_%d(x, d - 1);\n    return x;\n}\n" % nxt)

    # Expected result, computed with the same 32-bit arithmetic.
    def run(i, x, d):
        while True:
            ops, nxt = fns[i]
            for (mul, sh, add) in ops:
                x = (((x * mul) & MASK) ^ (x >> sh)) + add & MASK
            if d <= 0:
                return x
            i, d = nxt, d - 1

    starts = [rng.randrange(n_fns) for _ in range(CHAIN)]
    x = 0x12345678
    for s in starts:
        x = run(s, x, DEPTH)

    with open(os.path.join(a.out, "big_table.c"), "w", newline="\n") as c:
        c.write('#include "bigcode.h"\n')
        c.write("const bigfn big_table[%d] = {\n" % n_fns)
        for i in range(n_fns):
            c.write("    big_%d,\n" % i)
        c.write("};\n")
        c.write("const int big_starts[%d] = {%s};\n" % (CHAIN, ", ".join(map(str, starts))))
        c.write("const int big_chain = %d;\nconst int big_depth = %d;\n" % (CHAIN, DEPTH))
        c.write("const u32 big_expected = %uu;\n" % x)
        c.write("const int big_functions = %d;\n" % n_fns)

    print(f"{n_files} files, {n_fns} functions (~{n_fns * 1800 // (1024 * 1024)} MB of code expected); "
          f"expected checksum {x:08x}")


if __name__ == "__main__":
    main()
