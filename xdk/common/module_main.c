/*
 * module_main.c - runs one w2c2-translated WASI module on the Xbox 360 (or a
 * PC, for checking this file) and reports what it printed.
 *
 * Configure with macros (see each project's .vcxproj):
 *   SRT_MODULE          w2c2 module prefix, e.g. m5_guest
 *   SRT_MODULE_HEADER   its header, e.g. "guest.h"
 *   SPIRE_ROOT          folder mounted as the module's "/", e.g. "game:/selftest"
 *   SPIRE_SCRIPT        string fed to the module's stdin
 *   SPIRE_EXPECTED      optional: exact expected stdout; PASS/FAIL is reported
 *   SPIRE_SETUP_DATA    optional: create <root>/data/{one,two,three.bin} first
 *
 * Output goes to the debug output (Xenia's log), to <root>/log.txt and,
 * with the verdict and timing, to <root>/result.txt.
 */
#include "module_config.h"   /* per project, generated by tools/gen_xdk_tests.py */
#include "w2c2_base.h"
#include <stdio.h>
#include "srt.h"
#include "srt_plat.h"
#include SRT_MODULE_HEADER

#define SRT_CAT2(a, b) a##b
#define SRT_CAT(a, b) SRT_CAT2(a, b)
#define MOD_INSTANCE SRT_CAT(SRT_MODULE, Instance)
#define MOD_INSTANTIATE SRT_CAT(SRT_MODULE, Instantiate)
#define MOD_MEMORY SRT_CAT(SRT_MODULE, Export6_memory)
#define MOD_START SRT_CAT(SRT_MODULE, Export6_X5Fstart)

/* PC checks run the same code with the root redirected to a temp folder. */
#ifdef SPIRE_ROOT_OVERRIDE
#undef SPIRE_ROOT
#define SPIRE_ROOT SPIRE_ROOT_OVERRIDE
#endif
#ifndef SPIRE_ROOT
#define SPIRE_ROOT "game:/spire360test"
#endif
#ifndef SPIRE_SCRIPT
#define SPIRE_SCRIPT ""
#endif

static MOD_INSTANCE instance;
static char output[65536];
static size_t output_len = 0;

static void run_start(void* p) {
    MOD_START((MOD_INSTANCE*)p);
}

static void say(const char* text) {
    srt_plat_log(1, text, strlen(text));
}

static void write_file(const char* path, const char* text) {
    srt_file* f;
    size_t done;
    if (srt_plat_open(path, SRT_OPEN_WRITE | SRT_OPEN_CREATE | SRT_OPEN_TRUNC, &f) == 0) {
        srt_plat_write(f, text, strlen(text), &done);
        srt_plat_close(f);
    }
}

#ifdef SPIRE_SETUP_DATA
static void setup_data(void) {
    static const char* const names[3] = { "one", "two", "three.bin" };
    char path[256];
    int i;
    srt_plat_mkdir(SPIRE_ROOT "/data");
    for (i = 0; i < 3; i++) {
        sprintf(path, "%s/data/%s", SPIRE_ROOT, names[i]);
        write_file(path, names[i]);
    }
}
#endif

static int run(void) {
    srt_config cfg;
    static const char* const guest_argv[2] = { "guest", "alpha" };
    static const char* const guest_env[1] = { "SPIRE_TEST=yes" };
    char line[4096];
    char summary[512];
    srt_u64 t0;
    srt_u64 t1;
    int code;
    int pass = -1;

    srt_plat_mkdir(SPIRE_ROOT);
    srt_plat_set_log_file(SPIRE_ROOT "/log.txt");
    say("[spire360] module test starting\n");
#ifdef SPIRE_SETUP_DATA
    setup_data();
#endif

    memset(&cfg, 0, sizeof(cfg));
    cfg.root_dir = SPIRE_ROOT;
    cfg.argc = 2;
    cfg.argv = guest_argv;
    cfg.envc = 1;
    cfg.envp = guest_env;
    cfg.virtual_timers = 1;
    cfg.memory_limit = (srt_u64)256 * 1024 * 1024;
    if (srt_init(&cfg) != 0) {
        say("[spire360] srt_init failed\n");
        return 2;
    }

    t0 = srt_plat_time_monotonic_ns();
    MOD_INSTANTIATE(&instance, NULL);
    srt_set_memory(MOD_MEMORY(&instance));
    /* Hardware thread 2 = core 1, thread 0: where the game logic will run. */
    if (srt_guest_start(run_start, &instance, 0, 2) != 0) {
        say("[spire360] guest thread failed\n");
        return 2;
    }
    srt_stdin_write(SPIRE_SCRIPT, strlen(SPIRE_SCRIPT));
    srt_stdin_close();

    for (;;) {
        long n = srt_stdout_read_line(line, sizeof(line), 1);
        if (n < 0) {
            break;
        }
        say(line);
        say("\n");
        if (output_len + (size_t)n + 2 < sizeof(output)) {
            memcpy(output + output_len, line, (size_t)n);
            output_len += (size_t)n;
            output[output_len++] = '\n';
            output[output_len] = '\0';
        }
    }
    code = srt_guest_join();
    t1 = srt_plat_time_monotonic_ns();

#ifdef SPIRE_EXPECTED
    pass = strcmp(output, SPIRE_EXPECTED) == 0 && code == 0;
#endif
    sprintf(summary, "[spire360] exit %d, %lu ms, %s\n", code,
            (unsigned long)((t1 - t0) / 1000000),
            pass < 0 ? "no expected output" : (pass ? "PASS" : "FAIL"));
    say(summary);
    if (output_len + strlen(summary) + 1 < sizeof(output)) {
        strcpy(output + output_len, summary);
    }
    write_file(SPIRE_ROOT "/result.txt", output);
    return pass == 0 ? 1 : 0;
}

#ifdef _XBOX
void __cdecl main(void) {
    run();
}
#else
int main(void) {
    return run();
}
#endif
